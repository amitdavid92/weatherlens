"""Sensitivity of hub scores to the FEMA NRI normalization method (offline, from the snapshot).

    uv run python scripts/sensitivity.py [--out docs/PHASE_2_SENSITIVITY.md]

Methods compared (everything else in config/scoring.yaml unchanged):
  A percentile              national mid-rank percentile, no-exposure tier included (v1.0.0)
  B conditional_percentile  mid-rank percentile among positive-frequency counties only
  C hybrid                  0.5·A + 0.5·absolute log-frequency (1-in-100 yr -> 0, 1/yr -> 100)
"""

from __future__ import annotations

import argparse
import logging
import statistics
from datetime import date
from pathlib import Path

from weather_risk.analytics.config import Hazard, NriNormalization, load_scoring_config
from weather_risk.analytics.engine import AnalyticsEngine
from weather_risk.catalog import load_catalog
from weather_risk.config import PROJECT_ROOT, get_settings
from weather_risk.data.models import HazardCode
from weather_risk.data.repository import build_repository

METHODS = {
    "A percentile (v1.0.0)": NriNormalization(method="percentile"),
    "B conditional percentile": NriNormalization(method="conditional_percentile"),
    "C hybrid 50/50": NriNormalization(method="hybrid", relative_weight=0.5),
}


def engines() -> dict[str, AnalyticsEngine]:
    settings = get_settings().model_copy(update={"offline": True})
    base = load_scoring_config(PROJECT_ROOT / "config" / "scoring.yaml")
    catalog = load_catalog(settings.hubs_path)
    out = {}
    for name, norm in METHODS.items():
        cfg = base.model_copy(update={"nri_normalization": norm})
        out[name] = AnalyticsEngine(build_repository(settings), catalog, cfg,
                                    today=date(2026, 11, 25))  # fmt: skip
    return out


def f(x: float | None) -> str:
    return "—" if x is None else f"{x:.1f}"


def main() -> None:
    logging.disable(logging.WARNING)
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path)
    args = ap.parse_args()
    eng = engines()
    first = next(iter(eng.values()))
    hubs = [h.id for h in first.catalog.hubs]
    lines: list[str] = []
    w = lines.append
    w("# Phase 2 — Normalization Sensitivity Analysis (generated)\n")
    w("Generated by `scripts/sensitivity.py`, offline from the committed snapshot. Only the "
      "FEMA NRI normalization differs between columns; climate anchors, weights and data are "
      "identical.\n")  # fmt: skip

    # distribution context
    w("## National positive-frequency distributions (NRI Dec 2025, 50 states + DC)\n")
    w("| Hazard | Positive counties | No-exposure tier | Median positive AFREQ (/yr) | "
      "Share of positives ≥ 1/yr |")  # fmt: skip
    w("|---|---|---|---|---|")
    for code, d in first.percentiles().distributions.items():
        med = statistics.median(d.positives) if d.positives else None
        share = sum(1 for x in d.positives if x >= 1) / len(d.positives) if d.positives else 0
        w(f"| {code.name} | {len(d.positives)} | {d.n_no_exposure} | "
          f"{'—' if med is None else f'{med:.3g}'} | {share:.0%} |")  # fmt: skip
    w("")

    # key indicators
    w("## Key indicator scores\n")
    w("| Hub | Indicator | AFREQ (/yr) | " + " | ".join(METHODS) + " |")
    w("|---|---|---|" + "---|" * len(METHODS))
    for hub in ("dallas_tx", "miami_fl", "houston_tx", "chicago_il", "atlanta_ga"):
        for code in (HazardCode.HURRICANE, HazardCode.COASTAL_FLOODING):
            cells, raw = [], None
            for e in eng.values():
                rec = e.county(e.hub(hub))
                r = e.percentiles().score(rec, code)
                raw = rec.hazards[code].annualized_frequency
                cells.append(f(r.score))
            w(f"| {hub} | {code.name} | {'—' if raw is None else f'{raw:.4g}'} | "
              + " | ".join(cells) + " |")  # fmt: skip
    w("")

    # hazard + overall for all hubs
    for hz in (Hazard.HURRICANE, Hazard.FLOOD, None):
        title = hz.value if hz else "overall"
        w(f"## {title.capitalize()} score by method (rank among ranked hubs)\n")
        w("| Hub | " + " | ".join(METHODS) + " |")
        w("|---|" + "---|" * len(METHODS))
        ranks = {}
        for name, e in eng.items():
            r = e.rank_hubs(hazard=hz) if hz else e.rank_hubs()
            ranks[name] = {x.hub_id: x.rank for x in r.ranked}
        for hub in hubs:
            cells = []
            for name, e in eng.items():
                p = e.get_hub_profile(hub)
                s = p.hazards[hz].score if hz else p.overall_score
                rk = ranks[name].get(hub)
                cells.append(f"{f(s)} (#{rk})" if rk else f"{f(s)} (not ranked)")
            w(f"| {hub} | " + " | ".join(cells) + " |")
        w("")
    text = "\n".join(lines) + "\n"
    if args.out:
        args.out.write_text(text)
        print(f"wrote {args.out}")
    else:
        print(text)


if __name__ == "__main__":
    main()
