"""Render the four assignment scenarios + the 12-hub score table as Markdown (from real outputs)."""

from __future__ import annotations

from datetime import UTC, datetime

from weather_risk.analytics.config import ClimateMetric, Hazard
from weather_risk.analytics.engine import AnalyticsEngine
from weather_risk.analytics.formatting import format_score
from weather_risk.data.models import HazardCode, SourceId


def _f(x: float | None, nd: int = 1) -> str:
    return "—" if x is None else f"{x:.{nd}f}"


def _s(x: float | None) -> str:
    """0–100 score with the band-safe rounding policy (formatting.format_score)."""
    return "—" if x is None else format_score(x)


def _g(x: float | None) -> str:
    return "—" if x is None else f"{x:.4g}"


def render_scenarios(engine: AnalyticsEngine, *, offline: bool) -> str:
    cfg = engine.cfg
    out: list[str] = []
    w = out.append
    started = datetime.now(UTC)
    pct = engine.percentiles()

    w("# Phase 2 — Scenario Validation (generated)\n")
    w(f"Generated by `weather-risk scenarios` at {started.isoformat(timespec='seconds')} · "
      f"offline mode `{offline}` · methodology `{cfg.methodology_version}` · NRI "
      f"`{pct.nri_version}` · climate `{cfg.climate.source.value}` "
      f"{engine.climatology.label} · reference date {engine.today}.\n")  # fmt: skip
    w("All numbers are produced by the deterministic engine from the data layer; nothing is "
      "hardcoded and no LLM is involved. Scores are a heuristic **Weather Hazard Exposure Index** "
      "(0–100), not disruption probabilities.\n")  # fmt: skip

    # ------------------------------------------------------------- 12-hub table
    ranking = engine.rank_hubs()
    w("## Score table — all 12 hubs\n")
    w("| Rank | Hub | Region | Overall | Band | Status | Winter | Hurricane | Flood | Severe conv. "
      "| Extreme heat |")  # fmt: skip
    w("|---|---|---|---|---|---|---|---|---|---|---|")
    for e in ranking.ranked + ranking.not_ranked:
        p = engine.get_hub_profile(e.hub_id)
        hz = [f"{_s(p.hazards[h].score)}{'*' if p.hazards[h].status == 'partial' else ''}"
              for h in Hazard]  # fmt: skip
        w(f"| {e.rank if e.rank else 'not ranked'} | {p.hub_id} | {p.region} | "
          f"{_s(p.overall_score)} | {p.overall_band} | {p.overall_status} | " + " | ".join(hz)
          + " |")  # fmt: skip
    w("\n\\* partial hazard score (some indicator weight unavailable, renormalized). Partial "
      "overall results are reported but not ranked (`rank_partial_results: false`).\n")  # fmt: skip

    # ------------------------------------------------------------- scenario 1
    w("## Scenario 1 — Which Midwest hubs are most exposed to winter disruption?\n")
    r1 = engine.rank_hubs(hazard="winter", region="Midwest")
    w("| Rank | Hub | Winter score | Snow days/yr | Heavy-snow days/yr | Freezing days/yr | "
      "WNTW AFREQ (score) | ISTM AFREQ (score) | CWAV AFREQ (score) |")  # fmt: skip
    w("|---|---|---|---|---|---|---|---|---|")
    for e in r1.ranked + r1.not_ranked:
        inds = {
            i.indicator_id: i
            for i in engine.get_hub_profile(e.hub_id).hazards[Hazard.WINTER].indicators
        }

        def c(k: str, inds: dict = inds) -> str:
            i = inds[k]
            return f"{_f(i.raw_value)} ({_f(i.score)})"

        def n(k: str, inds: dict = inds) -> str:
            i = inds[k]
            return f"{_g(i.raw_value)} ({_f(i.score)})"

        w(f"| {e.rank} | {e.hub_id} | **{_f(e.score)}** | {c('snow_days_measurable')} | "
          f"{c('heavy_snow_days')} | {c('freezing_days')} | {n('nri_winter_weather')} | "
          f"{n('nri_ice_storm')} | {n('nri_cold_wave')} |")  # fmt: skip
    w("\nClimate columns: 2016–2025 annual averages from NOAA airport stations (indicator score in "
      "parentheses). NRI columns: annualized frequency (indicator score: hybrid of national percentile and absolute frequency, see SCORING_METHODOLOGY.md §3.2).\n")  # fmt: skip

    # ------------------------------------------------------------- scenario 2
    w("## Scenario 2 — Miami vs Houston: hurricane and flood exposure\n")
    c2 = engine.compare_hubs(["miami_fl", "houston_tx"], ["hurricane", "flood"])
    w("| Hazard | Miami score | Houston score | Higher | Difference |")
    w("|---|---|---|---|---|")
    for row in c2.rows:
        w(f"| {row.hazard.value} | {_f(row.hub_scores['miami_fl'])} | "
          f"{_f(row.hub_scores['houston_tx'])} | {row.leader or 'tie/—'} | {_f(row.difference)} |")  # fmt: skip
    w("\n| NRI hazard | Miami AFREQ | Miami score | Houston AFREQ | Houston score |")
    w("|---|---|---|---|---|")
    for code in (HazardCode.HURRICANE, HazardCode.COASTAL_FLOODING, HazardCode.INLAND_FLOODING):
        cells = []
        for hub in ("miami_fl", "houston_tx"):
            ind = next(i for row in c2.rows for i in row.indicators[hub]
                       if i.indicator_id.endswith(code.name.lower()))  # fmt: skip
            cells += [_g(c2.nri_raw[hub][code]["afreq"]), _f(ind.score)]
        w(f"| {code.name} ({code.value}) | " + " | ".join(cells) + " |")
    w(f"\nNRI {c2.nri_version}; AFREQ = annualized events (or event-days) per year over each "
      "hazard's own period of record. Flood uses FEMA flood frequencies, not rainfall; hurricane "
      "uses FEMA hurricane frequency, not observed wind.\n")  # fmt: skip

    # ------------------------------------------------------------- scenario 3
    w("## Scenario 3 — What percentage of days in Denver last year had snowfall?\n")
    for metric in (ClimateMetric.SNOW_DAYS_MEASURABLE, ClimateMetric.SNOW_DAYS_TRACE_INCLUSIVE):
        s = engine.get_weather_stat("denver_co", metric, "last year")
        cv = s.coverage
        w(f"- **{s.definition}** ({s.period.label}, NOAA {s.location_id}): "
          f"**{_f(s.value_percent_of_valid_days, 2)}%** = {s.event_days} / {cv.valid_days} valid "
          f"days · expected {cv.expected_days}, missing {cv.missing_days}, excluded "
          f"{cv.excluded_days}{(' ' + str(cv.excluded_reasons)) if cv.excluded_reasons else ''}, coverage {cv.coverage:.1%} "
          f"(status `{s.status}`)")  # fmt: skip
    s_om = engine.get_weather_stat("denver_co", ClimateMetric.SNOW_DAYS_MEASURABLE, "last year",
                                   source=SourceId.OPEN_METEO_ARCHIVE)  # fmt: skip
    w(f"- Alternative, modeled (Open-Meteo ERA5 grid {s_om.location_id}, reported separately, "
      f"never mixed): {_f(s_om.value_percent_of_valid_days, 2)}% of days with snowfall > 0 "
      f"({s_om.event_days}/{s_om.coverage.valid_days}).\n")  # fmt: skip

    w("### Insufficient coverage behaviour — Miami snowfall\n")
    sm = engine.get_weather_stat("miami_fl", ClimateMetric.SNOW_DAYS_MEASURABLE, "climatology")
    w(f"- {sm.period.label}: valid {sm.coverage.valid_days}/{sm.coverage.expected_days} days "
      f"({sm.coverage.coverage:.1%}) < required {sm.coverage.min_coverage:.0%} → status "
      f"`{sm.status}`, value `{sm.value_percent_of_valid_days}` (withheld, not zero).")  # fmt: skip
    mw = engine.get_hub_profile("miami_fl").hazards[Hazard.WINTER]
    w(f"- Miami winter hazard: `{mw.status}` ({mw.available_weight_fraction:.0%} of indicator weight "
      f"available) → overall `{engine.get_hub_profile('miami_fl').overall_status}` → listed under "
      "*not ranked* in the overall ranking.\n")  # fmt: skip

    # ------------------------------------------------------------- scenario 4
    w("## Scenario 4 — Why is the Dallas hub's weather disruption risk high?\n")
    e4 = engine.explain_hub_score("dallas_tx", claimed_band="High")
    pc = e4.premise_check
    w(f"**Premise check:** claim “{pc.claim}” → **supported = {pc.supported}**. {pc.reasoning}\n")
    w("Reframing: the index measures weather-hazard *exposure*; operational disruption risk "
      "cannot be assessed without internal downtime/shipment data.\n")  # fmt: skip
    w("| Hazard | Score | Band | Weight | Contribution to overall |")
    w("|---|---|---|---|---|")
    for h in e4.hazards_by_contribution:
        w(f"| {h.hazard.value} | {_f(h.score)} | {h.band} | {h.weight_in_overall:.2f} | "
          f"{_f(h.contribution_to_overall, 2)} |")  # fmt: skip
    w(f"| **overall** | **{_f(e4.overall_score)}** | **{e4.overall_band}** | 1.00 | "
      f"{_f(e4.overall_score, 2)} |\n")  # fmt: skip
    w(f"**Primary driver (hazard level): `{e4.primary_driver}`.** Hazard contributions above sum "
      "to the overall index.\n")  # fmt: skip
    w("Largest individual indicators (indicator level; a single-indicator hazard such as hurricane "
      "concentrates its whole weight in one indicator, so this list is not a hazard ranking):\n")  # fmt: skip
    w("| Indicator | Raw | Score | Weight in hazard | → hazard pts | → overall pts |")
    w("|---|---|---|---|---|---|")
    for i in e4.top_indicators:
        w(f"| `{i.hazard.value}.{i.indicator_id}` | {_g(i.raw_value)} | {_f(i.score)} | "
          f"{i.effective_weight_in_hazard:.3f} | {_f(i.contribution_to_hazard, 2)} | "
          f"{_f(i.contribution_to_overall, 2)} |")  # fmt: skip
    w(f"\nNot applicable (scored 0, kept in denominators): {e4.not_applicable or 'none'}. "
      f"Unavailable: {e4.unavailable or 'none'}.\n")  # fmt: skip

    # ------------------------------------------------------------- eligibility
    w("## Ranking eligibility (explicit)\n")
    w("| Hub | Overall eligible | Hazards not eligible | Reason |")
    w("|---|---|---|---|")
    for h in engine.catalog.hubs:
        el = engine.get_hub_profile(h).ranking_eligibility
        bad = [k for k, v in el.items() if k != "overall" and not v.eligible]
        reason = el["overall"].reason or "—"
        w(f"| {h.id} | {el['overall'].eligible} | {', '.join(bad) or '—'} | {reason} |")
    r_h = engine.rank_hubs(hazard="hurricane")
    r_f = engine.rank_hubs(hazard="flood")
    w(f"\nMiami in hurricane ranking: rank "
      f"{next((e.rank for e in r_h.ranked if e.hub_id == 'miami_fl'), None)}; in flood ranking: "
      f"rank {next((e.rank for e in r_f.ranked if e.hub_id == 'miami_fl'), None)} "
      "(complete hazards stay rankable even though Miami's overall score is partial).\n")  # fmt: skip

    # ------------------------------------------------------------- normalization
    w("## FEMA normalization in effect\n")
    norm = cfg.nri_normalization
    w(f"Method `{norm.method}`"
      + (f", relative weight {norm.relative_weight:g}, absolute log anchors "
         f"{norm.absolute_anchor.low:g}/yr → 0 and {norm.absolute_anchor.high:g}/yr → 100"
         if norm.method == "hybrid" else "")
      + ". See `docs/PHASE_2_SENSITIVITY.md` for the comparison with alternatives.\n")  # fmt: skip
    w("| Hub | HRCN AFREQ (/yr) | ≈ 1 event per N years | Relative (national pctl) | "
      "Absolute (log) | Final indicator score |")  # fmt: skip
    w("|---|---|---|---|---|---|")
    for h in engine.catalog.hubs:
        rec = engine.county(h)
        v = rec.hazards[HazardCode.HURRICANE]
        r = pct.score(rec, HazardCode.HURRICANE)
        per = f"{1 / v.annualized_frequency:.0f}" if v.annualized_frequency else "—"
        w(f"| {h.id} | {_g(v.annualized_frequency)} ({v.status.value}) | {per} | "
          f"{_f(r.relative_score)} | {_f(r.absolute_score)} | {_f(r.score)} |")  # fmt: skip
    w("")
    w(f"Generated in {(datetime.now(UTC) - started).total_seconds():.1f} s.")
    return "\n".join(out) + "\n"
